// Builds supabase/seed/colleges.sql from the U.S. Department of Education
// College Scorecard "Most Recent Institution-Level Data" CSV (public
// domain): https://collegescorecard.ed.gov/data/
//
//   node scripts/build-colleges-seed.mjs path/to/Most-Recent-Cohorts-Institution.csv
//
// Keeps institutions that are currently operating (CURROPER=1) and grant
// at least an associate degree (HIGHDEG >= 2) -- i.e. colleges and
// universities, not certificate-only trade programs. Re-running the seed
// is safe: rows upsert on the IPEDS id (unitid).
import fs from "node:fs";
import path from "node:path";

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/build-colleges-seed.mjs <Most-Recent-Cohorts-Institution.csv>");
  process.exit(1);
}

// Minimal RFC 4180 parser (quoted fields, escaped quotes, CRLF).
function parseCsv(text) {
  const rows = [];
  let row = [], field = "", inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else inQuotes = false;
      } else field += c;
    } else if (c === '"') inQuotes = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
    else if (c !== "\r") field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const [header, ...rows] = parseCsv(fs.readFileSync(src, "utf8"));
const col = (name) => {
  const i = header.indexOf(name);
  if (i === -1) throw new Error(`column ${name} not found`);
  return i;
};
const UNITID = col("UNITID"), NAME = col("INSTNM"), CITY = col("CITY"), STATE = col("STABBR");
const HIGHDEG = col("HIGHDEG"), CURROPER = col("CURROPER");

const q = (s) => (s ? `'${s.replace(/'/g, "''")}'` : "null");
const keep = rows.filter((r) => r[CURROPER] === "1" && Number(r[HIGHDEG]) >= 2 && r[NAME]);
keep.sort((a, b) => a[NAME].localeCompare(b[NAME]));

const out = [
  "-- Generated by scripts/build-colleges-seed.mjs from the U.S. Department of",
  "-- Education College Scorecard (public domain). Do not edit by hand.",
  `-- ${keep.length} currently operating, degree-granting U.S. institutions.`,
  "",
];
for (let i = 0; i < keep.length; i += 500) {
  out.push("insert into public.colleges (unitid, name, city, state) values");
  out.push(
    keep
      .slice(i, i + 500)
      .map((r) => `  (${Number(r[UNITID])}, ${q(r[NAME].trim())}, ${q(r[CITY].trim())}, ${q(r[STATE].trim())})`)
      .join(",\n"),
  );
  out.push("on conflict (unitid) do update set name = excluded.name, city = excluded.city, state = excluded.state;");
  out.push("");
}

const dest = path.join("supabase", "seed", "colleges.sql");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out.join("\n"));
console.log(`wrote ${keep.length} colleges to ${dest}`);
